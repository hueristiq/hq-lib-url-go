//go:build ignore

// Command tlds regenerates the official TLD/eTLD list. It is invoked via go:generate
// (see the module root) and is excluded from normal builds.
package main

import (
	"bufio"
	"errors"
	"flag"
	"fmt"
	"log"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strings"
	"text/template"
)

var (
	tldsTemplate = template.Must(template.New("tlds").Parse(`// This file is autogenerated by ./gen/main.go. Please do not edit manually.
package tlds

// Official is a sorted list of public top-level domains (TLDs) and effective top-level domains (eTLDs).
//
// TLDs are the highest level in the domain name system, while eTLDs include public suffixes,
// such as country code second-level domains (e.g., "co.uk" or "gov.in"), commonly used for websites.
//
// References:
// - IANA TLDs: https://data.iana.org/TLD/tlds-alpha-by-domain.txt
// - Public Suffix List: https://publicsuffix.org/list/public_suffix_list.dat
// - A-Z TLDs: https://tld-list.com/tlds-from-a-z
// - Wikipedia: https://en.wikipedia.org/wiki/Top-level_domain
var Official = []string{
{{- range $_, $TLD := .TLDs}}
	"{{$TLD}}",
{{- end}}
}
`))
	tldsFile string
)

func init() {
	flag.StringVar(&tldsFile, "output", "", "Specify the output file path for the generated Go source file.")

	flag.Usage = func() {
		h := "USAGE:\n"
		h += "  tlds [OPTIONS]\n"

		h += "\nOPTIONS:\n"
		h += " -output string    Specify the output file path for the generated Go source file.\n"

		fmt.Fprintln(os.Stderr, h)
	}

	flag.Parse()
}

func main() {
	if err := generate(); err != nil {
		log.Fatal(err)
	}
}

func generate() (err error) {
	if tldsFile == "" {
		return errors.New("output file path is required: use -output to specify the output file path")
	}

	log.Printf("Generating %s...\n", tldsFile)

	AZTLDs, err := getTLDsFromText()
	if err != nil {
		return fmt.Errorf("failed to get TLDs from text: %w", err)
	}

	IANATLDs, err := getTLDsFromIANA()
	if err != nil {
		return fmt.Errorf("failed to get TLDs from IANA: %w", err)
	}

	eTLDs, err := getEffectiveTLDsFromPublicSuffix()
	if err != nil {
		return fmt.Errorf("failed to get effective TLDs from the Public Suffix List: %w", err)
	}

	TLDs := append(AZTLDs, IANATLDs...)
	TLDs = append(TLDs, eTLDs...)

	slices.Sort(TLDs)

	TLDs = slices.Compact(TLDs)

	if err := writeTLDsToFile(TLDs, tldsFile); err != nil {
		return fmt.Errorf("failed to write TLDs to file: %w", err)
	}

	log.Println("TLDs file generated successfully.")

	return nil
}

func getTLDsFromText() (TLDs []string, err error) {
	file, err := os.Open("./tlds/gen/TLDs.txt")
	if err != nil {
		return nil, fmt.Errorf("failed to open TLDs file: %w", err)
	}

	defer file.Close()

	scanner := bufio.NewScanner(file)

	for scanner.Scan() {
		TLD := scanner.Text()

		if TLD == "" {
			continue
		}

		TLDs = append(TLDs, TLD)
	}

	if err = scanner.Err(); err != nil {
		return nil, fmt.Errorf("scanner error: %w", err)
	}

	return TLDs, nil
}

func getTLDsFromIANA() (TLDs []string, err error) {
	var res *http.Response

	res, err = http.Get("https://data.iana.org/TLD/tlds-alpha-by-domain.txt")
	if err != nil {
		return nil, fmt.Errorf("failed to fetch IANA TLDs: %w", err)
	}

	defer res.Body.Close()

	if res.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("unexpected HTTP status %s while fetching IANA TLDs", res.Status)
	}

	re := regexp.MustCompile(`^[^#]+$`)

	scanner := bufio.NewScanner(res.Body)

	for scanner.Scan() {
		line := scanner.Text()

		line = strings.TrimSpace(line)
		line = strings.ToLower(line)

		TLD := re.FindString(line)

		if TLD == "" || strings.HasPrefix(TLD, "xn--") {
			continue
		}

		TLDs = append(TLDs, TLD)
	}

	if err = scanner.Err(); err != nil {
		return nil, fmt.Errorf("scanner error: %w", err)
	}

	return TLDs, nil
}

// getEffectiveTLDsFromPublicSuffix collects the ICANN section of the Public Suffix List.
// The PSL is only approximated: wildcard rules ("*." prefixes) are treated as plain
// suffixes, and exception rules ("!" prefixes) are ignored entirely, so the generated
// list may both over- and under-approximate the true public suffix set.
func getEffectiveTLDsFromPublicSuffix() (eTLDs []string, err error) {
	var res *http.Response

	res, err = http.Get("https://publicsuffix.org/list/effective_tld_names.dat")
	if err != nil {
		return nil, fmt.Errorf("failed to fetch the Public Suffix List: %w", err)
	}

	defer res.Body.Close()

	if res.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("unexpected HTTP status %s while fetching the Public Suffix List", res.Status)
	}

	scanner := bufio.NewScanner(res.Body)

	for scanner.Scan() {
		line := scanner.Text()

		line = strings.TrimSpace(line)

		if strings.HasPrefix(line, "// ===BEGIN PRIVATE DOMAINS") {
			break
		}

		if strings.HasPrefix(line, "//") {
			continue
		}

		TLD := line

		TLD = strings.ReplaceAll(TLD, "*.", "")
		TLD = strings.ReplaceAll(TLD, "!", "")

		if TLD == "" {
			continue
		}

		eTLDs = append(eTLDs, TLD)
	}

	if err = scanner.Err(); err != nil {
		return nil, fmt.Errorf("scanner error: %w", err)
	}

	return eTLDs, nil
}

func writeTLDsToFile(TLDs []string, TLDsFile string) (err error) {
	file, err := os.Create(TLDsFile)
	if err != nil {
		err = fmt.Errorf("failed to create output file: %w", err)

		return
	}

	defer file.Close()

	data := struct {
		TLDs []string
	}{
		TLDs: TLDs,
	}

	if err := tldsTemplate.Execute(file, data); err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	return
}
