// Command schemesgen regenerates the official IANA URL scheme list.
//
// It fetches the active entries from the IANA registry and emits the sorted list used
// by the schemes package. Run go generate from the module root.
package main

import (
	"context"
	"encoding/csv"
	"errors"
	"flag"
	"fmt"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"strings"
	"text/template"
)

// schemesTemplate renders the generated schemes source file.
var schemesTemplate = template.Must(template.New("schemes").Parse(`// Code generated by cmd/schemesgen; DO NOT EDIT.

package scheme

// Official is a sorted list of the active IANA-assigned URL schemes.
//
// This list is periodically updated from the IANA registry to ensure accuracy.
// Historical and otherwise obsolete entries are excluded.
//
// Reference:
// - https://www.iana.org/assignments/uri-schemes/uri-schemes-1.csv
var Official = []string{
{{- range $scheme := .Schemes}}
	"{{$scheme}}",
{{- end}}
}
`))

// schemeStatusColumn is the 0-based index of the Status column in the IANA CSV.
const schemeStatusColumn = 3

// schemesCSVURL is the canonical location of the IANA scheme registry CSV.
const schemesCSVURL = "https://www.iana.org/assignments/uri-schemes/uri-schemes-1.csv"

// excludedSchemes names schemes excluded from the official list although the IANA
// registry still marks them active. The Z39.50 retrieval and session schemes belong to
// the long-defunct Z39.50 protocol family, whose base "z39.50" scheme the registry
// itself marks Historical.
var excludedSchemes = map[string]struct{}{
	"z39.50r": {},
	"z39.50s": {},
}

// main parses the command-line flags and regenerates the official scheme list.
func main() {
	output := flag.String("output", "", "path of the generated Go file")

	flag.Parse()

	if *output == "" {
		log.Fatal("output file path is required: use -output to specify it")
	}

	if err := generate(*output); err != nil {
		log.Fatal(err)
	}
}

// generate fetches the IANA scheme registry and writes the generated list to output.
//
// Parameters:
//   - output (string): the path of the generated Go file.
//
// Returns:
//   - err (error): non-nil when the registry cannot be fetched or the file cannot be
//     written.
func generate(output string) (err error) {
	log.Printf("Generating %s...\n", output)

	schemes, err := fetchSchemesList()
	if err != nil {
		return fmt.Errorf("failed to fetch schemes: %w", err)
	}

	if err = writeSchemesToFile(schemes, output); err != nil {
		return fmt.Errorf("failed to write schemes to file: %w", err)
	}

	log.Println("Schemes file generated successfully.")

	return nil
}

// fetchSchemesList downloads the IANA scheme registry and returns its active schemes.
//
// Returns:
//   - schemes ([]string): the sorted, de-duplicated active scheme names.
//   - err (error): non-nil when the registry cannot be fetched or parsed.
func fetchSchemesList() (schemes []string, err error) {
	req, err := http.NewRequestWithContext(context.Background(), http.MethodGet, schemesCSVURL, http.NoBody)
	if err != nil {
		return nil, fmt.Errorf("failed to build the schemes request: %w", err)
	}

	res, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, fmt.Errorf("failed to fetch the schemes CSV: %w", err)
	}

	defer func() { _ = res.Body.Close() }()

	if res.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("unexpected HTTP status %s while fetching the schemes CSV", res.Status)
	}

	reader := csv.NewReader(res.Body)

	if _, err = reader.Read(); err != nil {
		return nil, fmt.Errorf("failed to read CSV header: %w", err)
	}

	for {
		record, readErr := reader.Read()
		if errors.Is(readErr, io.EOF) {
			break
		}

		if readErr != nil {
			return nil, fmt.Errorf("failed to read CSV row: %w", readErr)
		}

		if len(record) <= schemeStatusColumn {
			return nil, fmt.Errorf("unexpected CSV row width %d", len(record))
		}

		// Obsolete entries are identified by the Status column (not the name column):
		// skip Historical entries as well as names that carry the registry's
		// "(OBSOLETE)" marker.
		if record[schemeStatusColumn] == "Historical" || strings.Contains(record[0], "OBSOLETE") {
			continue
		}

		if _, excluded := excludedSchemes[record[0]]; excluded {
			continue
		}

		schemes = append(schemes, record[0])
	}

	slices.Sort(schemes)

	schemes = slices.Compact(schemes)

	return schemes, nil
}

// writeSchemesToFile renders schemes and writes the result to output.
//
// Parameters:
//   - schemes ([]string): the scheme names to emit.
//   - output (string): the path of the generated Go file.
//
// Returns:
//   - err (error): non-nil when the file cannot be created or the template cannot be
//     executed.
func writeSchemesToFile(schemes []string, output string) (err error) {
	file, err := os.Create(output) //nolint:gosec // G304: output is a local CLI argument
	if err != nil {
		return fmt.Errorf("failed to create output file: %w", err)
	}

	defer func() { _ = file.Close() }()

	data := struct {
		Schemes []string
	}{
		Schemes: schemes,
	}

	if err = schemesTemplate.Execute(file, data); err != nil {
		return fmt.Errorf("failed to execute template: %w", err)
	}

	return nil
}
